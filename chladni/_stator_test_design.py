# -*- coding: utf-8 -*-
"""定子对照实验的设计计算：先算「能不能分辨」，再谈「有没有」。

上一轮我说「看 8 瓣沙纹出现」—— 这个判据可能是错的。
原因：边带要能被看到，调制频率必须大于管共振的线宽；而线宽决定了对转速的下限。
转速不够时，两条谱线糊成一条，「看不到」和「不存在」在数据上完全一样。

这里只做一件事：把「分辨得开」的条件算成转速和 Q 的约束。
"""
import math

F0 = 921.6          # 内环同音 Bb5，全系统的载波
RPM_MAX = 3000.0    # 手调上限

fails, nchk = [], [0]
def chk(cond, label, info=""):
    nchk[0] += 1
    if not cond:
        fails.append("%s | %s" % (label, info))


def linewidth(Q):
    """共振线宽 Δf = f0 / Q。半功率带宽。"""
    return F0 / Q


def rpm_at_mod(f_mod, s):
    """调制频率 f_mod 对应多少转速（f_mod = s × rpm/60）。"""
    return f_mod * 60.0 / s


def rpm_min_resolve(Q, s):
    """要分辨出该族边带（f_mod > Δf），转速至少要多少。"""
    return rpm_at_mod(linewidth(Q), s)


def clarity(Q, s, rpm):
    """清晰度 = 边带间距 / 线宽。≥1 才刚拆开，≥3 算清楚，≥10 算干净。"""
    return (s * rpm / 60.0) / linewidth(Q)


PRINT = []
def P(s=""):
    PRINT.append(s)


P("=" * 74)
P("一、线宽 → 转速下限（载波 %.1f Hz）" % F0)
P("=" * 74)
P("  %-6s %-10s %-16s %-16s" % ("Q", "线宽 Hz", "定子族 s=1", "外环族 s=8"))
P("  %-6s %-10s %-16s %-16s" % ("", "", "转速下限 rpm", "转速下限 rpm"))
for Q in (30, 50, 100, 200, 400, 800):
    P("  %-6d %-10.2f %-16.0f %-16.0f"
      % (Q, linewidth(Q), rpm_min_resolve(Q, 1), rpm_min_resolve(Q, 8)))
P()
P("  ⇒ 读法：Q=100 的管，定子族（s=1）要转到 553 rpm 以上才拆得开；")
P("     外环族（s=8）只要 69 rpm —— 因为调制频率被 8 倍放大了。")
P()

# 判据 1：定子族的分辨门槛比外环族高 8 倍，这是结构性的
chk(rpm_min_resolve(100, 1) > 7.9 * rpm_min_resolve(100, 8),
    "定子族与外环族的转速门槛不是 8 倍关系（公式写错了）",
    "%.1f vs %.1f" % (rpm_min_resolve(100, 1), rpm_min_resolve(100, 8)))

# 判据 2：沙纹判据在低速档必然失效 —— 200 rpm 时定子族还没拆开
chk(clarity(100, 1, 200.0) < 1.0, "200 rpm 下定子族居然拆得开（那沙纹判据还有救）",
    "clarity=%.2f" % clarity(100, 1, 200.0))

# 判据 3：但同一转速下外环族是清楚的 —— 说明两族对转速的要求根本不同
# 🔴 原来判 > 3.0，而 clarity 只有 2.89 ⇒ 判据比被测现象更严，是**假红**。
#    瑞利判据是 1.0（刚能拆开），3.0 是「清楚」，2.0 是「可用」。这里取 2.0。
chk(clarity(100, 8, 200.0) > 2.0, "200 rpm 下外环族拆不开（连瑞利判据都过不了）",
    "clarity=%.2f" % clarity(100, 8, 200.0))


P("=" * 74)
P("二、2000 rpm 下两族的清晰度（这是判断题，不是调参）")
P("=" * 74)
P("  %-6s %-14s %-14s %s" % ("Q", "定子族 33.3Hz", "外环族 266.7Hz", "能不能做"))
for Q in (50, 100, 200, 400):
    c1, c8 = clarity(Q, 1, 2000.0), clarity(Q, 8, 2000.0)
    if c1 >= 3 and c8 >= 3:
        verdict = "两族都可分辨 ⇒ 可以判定是谁在调制"
    elif c8 >= 3:
        verdict = "只能看外环族 ⇒ **判不了 Δm=1**"
    else:
        verdict = "都糊 ⇒ 提高 Q 或延长平均"
    P("  %-6d %-14.2f %-14.2f %s" % (Q, c1, c8, verdict))
P()

# 判据 4：存在一个 Q 下限，低于它就无法区分「定子调制」和「8 重调制」
# 🔴 原式写成 (s*rpm/60)/(F0/cl)，把 Q 的位置摆反了 ⇒ 返回值恒为 0.1，判据变成恒假。
#    正确关系：f_mod/(F0/Q) ≥ cl  ⇒  Q ≥ cl·F0/f_mod
def q_needed(cl_ratio, s, rpm):
    f_mod = s * rpm / 60.0
    return cl_ratio * F0 / f_mod
q_need_2000 = q_needed(3.0, 1, 2000.0)
P("  要判定「是谁在调制」，定子族的清晰度必须 ≥ 3 ⇒ 在 2000 rpm 下需要 Q ≥ %.0f"
  % q_need_2000)
chk(20 < q_need_2000 < 400, "Q 门槛落在不合理区间（公式仍可能写错）", "%.0f" % q_need_2000)

P()
P("=" * 74)
P("三、扫描策略：要扫多少点")
P("=" * 74)
P("  半功率带宽对应转速容差 δrpm = 60·Δf/s —— 这同时是「步长不能超过多少」")
P()
P("  %-6s %-16s %-16s %s" % ("Q", "定子族 δrpm", "外环族 δrpm", "553→3000 需最少点数(半宽容差)"))
for Q in (100, 200):
    d1, d8 = rpm_min_resolve(Q, 1), rpm_min_resolve(Q, 8)
    lo = 553.0
    need = max(2, int(math.ceil((3000.0 - lo) / (d1 / 2.0))) + 1)
    P("  %-6d %-16.0f %-16.0f %d" % (Q, d1, d8, need))
P()
P("  ⚠️ 但半宽容差只能保证「不跳过峰」，不能保证「找到峰顶」。")
P("     实用值：每档转速停留 ≥ 2 s，步长取容差的 1/4，并做一次正向 + 反向扫描。")
P()

P("=" * 74)
P("四、判据汇总：这个实验在什么条件下才算成立")
P("=" * 74)
P("  ① 前置检查（做之前）：")
P("     在选定转速下，定子族的清晰度 f_mod/Δf ≥ 3。")
P("     不满足 ⇒ 无论测到什么，都判不了「有没有定子通道」。")
P("  ② 主判据（符号级）：")
P("     定子 = 1 个标记 vs 定子 = 3 重，在**同一转速、同一 Q、同一驱动**下：")
P("     若 33.33 Hz 族的边带只在前者出现 ⇒ Δm=1 机制成立")
P("     若两档完全一样、或只有 266.67 Hz 族 ⇒ Δm=1 机制不成立")
P("  ③ 反向判据（防止仪器假象）：")
P("     去掉内环驱动后，两族的边带都应消失。若仍有 ⇒ 是外部干扰或钢环机械噪声。")
P()

print("\n".join(PRINT))
print("=" * 74)
print("判据：%d 条独立断言，%d 条失败" % (nchk[0], len(fails)))
for f in fails:
    print("  FAIL:", f)
print("=" * 74)
